-- Site events: "search started" and "booking link clicked" (Phase 1 of "know what earns money", Nov 2026).
-- Run ONCE in the Supabase SQL editor. Only the server writes here (service key, /api/event); RLS is on with no policies,
-- so the public key can neither read nor write. No personal data: no IP address, no browser details, no cookies.
create table if not exists site_events (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  name text not null check (name in ('search', 'book_click')),
  page text,      -- book_click: the screen (lib/subId.ts LinkPage)
  trip text,      -- 'ow' one way, 'rt' round trip, 'two' two one-way tickets
  airport text,   -- book_click: the home airport the trip starts from (lowercase)
  mode text,      -- search: 'exact' | 'month' | 'range'
  anywhere boolean -- search: Anywhere or a named destination
);
create index if not exists site_events_at on site_events (at desc);
alter table site_events enable row level security;
